<?php

declare(strict_types=1);

namespace App\Enum\Purchase;

/**
 * Где заявка стоит в маршруте.
 *
 * Статус хранится, а не вычисляется. Прежде указатель считался на месте —
 * минимальной незакрытой позицией среди загруженных шагов, — и это стоило двух
 * вещей. Списки и очередь директора не могли спросить «чей сейчас этап» запросом,
 * им приходилось поднимать все шаги заявки. И, что важнее, закрытие этапа
 * оказывалось решением, принятым в памяти процесса: два согласанта параллельного
 * этапа, нажавшие одновременно, оба видели «этап ещё не закрыт», и уведомление
 * следующим либо уходило дважды, либо не уходило вовсе.
 *
 * Цена — статус нужно держать согласованным с решениями задач. Поэтому писатель
 * у него один, PurchaseApprovalWorkflow, и меняется он только вместе с версией
 * заявки.
 *
 * Отказа среди статусов нет намеренно. Отказ — это решение задачи, а не состояние
 * этапа: заявка уходит в REJECTED целиком, и остальные этапы так и остаются
 * незакрытыми. Поэтому спрашивать «чей этап» имеет смысл только у заявки на
 * согласовании — у возвращённой автору активный этап формально есть, но никого
 * не ждёт.
 */
enum PurchaseStageStatus: string
{
    /** Очередь ещё не дошла. */
    case PENDING = 'PENDING';

    /**
     * Этап есть в маршруте, но задач в нём пока нет: согласантов выбирает
     * директор на разборе, и до его решения неизвестно, кто они.
     *
     * Отдельный статус, а не пустой PENDING, потому что это состояние видно
     * заявителю и согласантам в карточке — «профильные замы, ожидает назначения».
     * Пустой этап без такой отметки читался бы как дырка в маршруте.
     */
    case AWAITING_ASSIGNMENT = 'AWAITING_ASSIGNMENT';

    /** Указатель здесь: задачи этапа ждут решения. */
    case ACTIVE = 'ACTIVE';

    /** Закрыт по правилу этапа. */
    case COMPLETED = 'COMPLETED';

    /**
     * Пройден без решений.
     *
     * Штатный случай ровно один: директор на разборе не отметил ни одного
     * согласанта. Пустой этап нельзя ни закрыть, ни оставить активным — заявка
     * встала бы навсегда, ожидая тех, кого не назначили.
     */
    case SKIPPED = 'SKIPPED';

    public function getLabel(): string
    {
        return match ($this) {
            self::PENDING => 'Ожидает очереди',
            self::AWAITING_ASSIGNMENT => 'Ожидает назначения',
            self::ACTIVE => 'На согласовании',
            self::COMPLETED => 'Согласован',
            self::SKIPPED => 'Пропущен',
        };
    }

    /** Этап пройден: указатель может идти дальше. */
    public function isClosed(): bool
    {
        return $this === self::COMPLETED || $this === self::SKIPPED;
    }
}

<?php

declare(strict_types=1);

namespace App\Enum\Purchase;

/**
 * Полномочия модуля закупок: то, что нельзя выразить шагом маршрута.
 *
 * Набор закрытый и намеренно короткий. Всё, что можно спросить у маршрута,
 * здесь отсутствует: «кто подписывает» — адресат шага, «кто ведёт ресёрч» —
 * назначение шага. Полномочия остались только там, где спрашивать нечего:
 * до подачи и после того, как маршрут пройден.
 *
 * В админке они раздаются ролям галочками, поэтому роль «Помощник закупок» с
 * одним справочником и без надзора заводится без правки кода. Роли и код
 * связаны только через этот enum: колонки «это отдел закупок» в справочнике
 * ролей нет и быть не должно — иначе гейты вернутся к сравнению с константой.
 */
enum PurchaseCapability: string
{
    /** Видеть все заявки модуля, а не только свои и те, где ты в маршруте. */
    case VIEW_ALL = 'VIEW_ALL';

    /** Категории, настройки модуля и классификация заявки (закон, способ закупки). */
    case MANAGE_DICTIONARIES = 'MANAGE_DICTIONARIES';

    /**
     * Конвейер исполнения: оплата счёта, отметка доставки, закрытие в архив.
     * После APPROVED маршрут пройден, шагов больше нет — выразить это нечем.
     */
    case RUN_EXECUTION = 'RUN_EXECUTION';

    /** Приоритет и отмена любой заявки до финала — вмешательство помимо маршрута. */
    case SUPERVISE = 'SUPERVISE';

    public function getLabel(): string
    {
        return match ($this) {
            self::VIEW_ALL => 'Видеть все заявки',
            self::MANAGE_DICTIONARIES => 'Справочники и классификация',
            self::RUN_EXECUTION => 'Конвейер исполнения',
            self::SUPERVISE => 'Приоритет и отмена заявок',
        };
    }
}

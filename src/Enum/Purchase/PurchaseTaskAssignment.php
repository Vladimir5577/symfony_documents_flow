<?php

declare(strict_types=1);

namespace App\Enum\Purchase;

/**
 * Чем адресована задача этапа.
 *
 * Заменяет PurchaseApproverKind, где USER означал две разные вещи в зависимости
 * от того, в какой таблице лежит строка: в заготовке маршрута — «здесь будут
 * люди, которых выберет директор», в шагах заявки — «подписывает вот этот
 * человек». Одно значение на два смысла означало, что прочитать строку в отрыве
 * от её таблицы нельзя, а правило «слот замов нельзя адресовать ролью» приходилось
 * держать в редакторе, потому что в самих данных оно не выражалось.
 *
 * Теперь смыслы разведены, и каждый из них законен только на своей стороне:
 * DYNAMIC_USERS бывает лишь в заготовке, USER — лишь в снимке заявки. Пул, из
 * которого выбирают, задаётся полем задачи, а не зашит в код: благодаря этому
 * динамических этапов в маршруте может быть сколько нужно и с разными пулами —
 * профильные замы на одном, служба безопасности на другом. Прежде такой этап был
 * ровно один, потому что позиция под него хранилась единственным числом на заявке.
 */
enum PurchaseTaskAssignment: string
{
    /** Закроет любой носитель роли. */
    case ROLE = 'ROLE';

    /**
     * Место под людей, которых выберет разбирающий заявку из заданного пула.
     * Только в заготовке маршрута: в снимке заявки такие задачи уже превращены
     * в USER — по одной на каждого выбранного.
     */
    case DYNAMIC_USERS = 'DYNAMIC_USERS';

    /**
     * Закроет автор заявки.
     *
     * Нужно там, где действие по смыслу его: товар приходит к заявителю, и
     * поставку подтверждает он. Раньше это было исключением в правах — «или
     * автор, если статус доставки», — то есть участие заявителя в процессе знал
     * код, а не маршрут.
     */
    case AUTHOR = 'AUTHOR';

    /**
     * Закроет конкретный человек. Только в снимке заявки: в маршрут людей
     * поимённо не вписывают.
     *
     * Заготовка адресует роли, а не сотрудников, сознательно: сотрудник уходит в
     * отпуск, меняет отдел и увольняется, а маршрут остаётся, и заявки встали бы
     * на человеке, которого уже нет. Если подписант действительно должен быть
     * один — это роль с одним носителем, и состав носителей меняется в админке.
     */
    case USER = 'USER';

    /**
     * Подписи отвечают на вопрос «кто закроет задачу», а не называют механизм:
     * админ в редакторе маршрута выбирает адресата, и «Роль» на этот вопрос не
     * отвечает — непонятно, один носитель или любой.
     */
    public function getLabel(): string
    {
        return match ($this) {
            self::ROLE => 'Любой в роли',
            self::DYNAMIC_USERS => 'Кого выберет разбирающий',
            self::AUTHOR => 'Автор заявки',
            self::USER => 'Конкретный сотрудник',
        };
    }

    /**
     * Чем можно адресовать задачу в заготовке маршрута.
     *
     * @return list<self>
     */
    public static function templateAssignments(): array
    {
        return [self::ROLE, self::DYNAMIC_USERS, self::AUTHOR];
    }

    /** Значение допустимо в заготовке маршрута. */
    public function isAllowedInTemplate(): bool
    {
        return in_array($this, self::templateAssignments(), true);
    }
}

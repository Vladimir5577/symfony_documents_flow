<?php

declare(strict_types=1);

namespace App\Enum\Purchase;

/**
 * Назначение этапа маршрута: что на нём делают, а не кто его закрывает.
 *
 * Назначение переехало с задачи на этап намеренно. Пока оно жило на шаге, ничто
 * не мешало поставить на одну позицию подпись бухгалтерии и ресёрч закупок — и
 * заявка оказывалась одновременно на ресёрче и на согласовании: границу возврата
 * искали по назначению шага, а нашли бы её посреди группы подписей. У этапа
 * назначение одно по построению, и такое состояние стало невыразимым.
 *
 * Роль отвечает только на вопрос «кто подписывает» и в шаблоне меняется свободно.
 *
 * TRIAGE в маршруте не больше одного — это отличие от прежней модели, где оба
 * визита директора были разбором. Разбор — это не «директор смотрит», а особые
 * права: правка состава заявки, выбор согласантов, смена маршрута. Второй визит
 * директора ничего из этого не даёт, это обычная подпись, то есть SIGN_OFF.
 * Пока назначение означало две вещи, отличать их приходилось сравнением позиций.
 *
 * Быстрый маршрут разбора не имеет вовсе: заявка сразу уходит в отдел закупок.
 * Поэтому правило — «не больше одного», а не «ровно один».
 *
 * Исполнение после согласования — тоже этапы этого же маршрута. Раньше это была
 * зашитая цепочка статусов со своими правилами «кому можно», и «доставку
 * подтверждает склад, а не заявитель» стоило релиза, тогда как «добавить в
 * согласование охрану» стоило правки в админке. Требования одного порядка не
 * должны стоить по-разному.
 */
enum PurchaseStagePurpose: string
{
    /**
     * Разбор: с этого этапа правят состав заявки, выбирают согласантов и меняют
     * маршрут. В маршруте не больше одного.
     */
    case TRIAGE = 'TRIAGE';

    /**
     * Ресёрч: поставщик, реальные цены, документы. Закрывший этап становится
     * исполнителем заявки, а сам этап — границей, на которую откатывают заявку
     * идущие после: они бракуют пакет документов, а не заявку.
     */
    case SOURCING = 'SOURCING';

    /** Обычная подпись: согласующий смотрит готовый пакет и решает. */
    case SIGN_OFF = 'SIGN_OFF';

    /** Счёт оплачен. */
    case PAYMENT = 'PAYMENT';

    /** Товар получен — обычно подтверждает заявитель, к нему он и приходит. */
    case DELIVERY = 'DELIVERY';

    /** Закрытие в архив: закрывающие документы приложены. */
    case CLOSING = 'CLOSING';

    public function getLabel(): string
    {
        return match ($this) {
            self::TRIAGE => 'Разбор заявки',
            self::SOURCING => 'Ресёрч и документы',
            self::SIGN_OFF => 'Согласование',
            self::PAYMENT => 'Оплата',
            self::DELIVERY => 'Поставка',
            self::CLOSING => 'Закрытие',
        };
    }

    /**
     * Этап исполнения, а не согласования.
     *
     * Различие нужно редактору маршрутов: исполнение идёт после согласования, и
     * маршрут, где оплата стоит перед подписью финдиректора, — это ошибка
     * настройки, а не экзотический регламент. Поведение этапа из назначения при
     * этом не выводится: отказ и возврат в закупки включаются полями этапа,
     * иначе назначение снова начнёт означать несколько вещей.
     */
    public function isExecution(): bool
    {
        return match ($this) {
            self::PAYMENT, self::DELIVERY, self::CLOSING => true,
            self::TRIAGE, self::SOURCING, self::SIGN_OFF => false,
        };
    }
}

<?php

declare(strict_types=1);

namespace App\Enum\Purchase;

/**
 * Назначение шага маршрута: что на нём делают, а не кто его закрывает.
 *
 * Логика модуля спрашивает именно назначение. Раньше она спрашивала роль
 * («шаг отдела закупок — значит ресёрч») и позицию («шаг 4 —
 * значит замы»), поэтому переименование роли или перестановка шагов ломали
 * исполнителя, границу возврата и модалку директора. Роль отвечает только на
 * вопрос «кто подписывает» и в шаблоне маршрута свободно меняется.
 *
 * Назначения намеренно мало и оно не про должности: SIGN_OFF — обычная подпись,
 * и таких шагов в маршруте может быть сколько угодно. Особые — только те два,
 * на которых заявка меняется, а не просто согласуется.
 */
enum PurchaseStepPurpose: string
{
    /**
     * Разбор: с этого шага правят состав заявки и назначают согласантов.
     * У обычной заявки таких шагов два — первичное решение директора и итоговое.
     */
    case TRIAGE = 'TRIAGE';

    /**
     * Ресёрч: поставщик, реальные цены, документы. Закрывший шаг становится
     * исполнителем заявки, а сама позиция — границей, на которую откатывают
     * заявку те, кто идёт после: они бракуют пакет документов, а не заявку.
     */
    case SOURCING = 'SOURCING';

    /** Обычная подпись: согласующий смотрит готовый пакет и решает. */
    case SIGN_OFF = 'SIGN_OFF';

    public function getLabel(): string
    {
        return match ($this) {
            self::TRIAGE => 'Разбор заявки',
            self::SOURCING => 'Ресёрч и документы',
            self::SIGN_OFF => 'Согласование',
        };
    }

    /** @return array<string, string> [value => label] */
    public static function getChoices(): array
    {
        $choices = [];
        foreach (self::cases() as $case) {
            $choices[$case->value] = $case->getLabel();
        }

        return $choices;
    }
}
